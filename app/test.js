const { chromium } = require('playwright');
(async () => {
  const [,, page_path, outdir] = process.argv;
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const p = await b.newPage({ viewport: { width: 1180, height: 820 }, deviceScaleFactor: 1 });
  const errs = [];
  p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await p.goto('file://' + page_path); await p.waitForTimeout(1200);
  const shot = async (n) => { await p.waitForTimeout(500); await p.screenshot({ path: `${outdir}/${n}.png` }); };
  const chip = async (container, text) => { const bs = await p.$$(`#${container} button`); for (const bt of bs) { const t = (await bt.innerText()).trim(); if (t.includes(text)) { await bt.click(); return true; } } console.log('no chip', container, text); return false; };
  await shot('a_shape');
  await chip('mChips', 'C3'); await p.waitForTimeout(1900); await shot('b_c3');
  await chip('mChips', 'σv (2)'); await p.waitForTimeout(1900); await chip('mChips2', 'σv planes'); await shot('c_sv2');
  await p.click('#mStep button[data-v="frag"]'); await chip('mChips', 'e(x)'); await shot('d_frag');
  await p.click('#mStep button[data-v="match"]'); await chip('mChips', 'N 2px'); await shot('e_match_px_a1');
  await chip('mChips2', 'e(x)'); await shot('f_match_px_ex');
  await chip('mChips', 'N 2pz'); await chip('mChips2', 'a1'); await shot('f2_match_pz');
  await p.click('#mStep button[data-v="mo"]'); await shot('g_mo_3a1');
  await chip('mChips', '1e (x)'); await shot('h_mo_1ex');
  await chip('mChips', '4a1'); await shot('h2_mo_4a1');
  await p.click('#t-unit-cells'); await p.waitForTimeout(600); await shot('i_cells');
  await chip('cChips', 'Touching line'); await shot('j_line');
  await p.click('#cStyle button[data-v="hard"]'); await shot('k_hard');
  await p.click('#cStruct button[data-v="fcc"]'); await chip('cChips', 'Pythagoras'); await shot('l_fcc_pyth');
  await p.click('#mSel button[data-m="W"]'); await shot('m_W');
  await chip('cChips', 'a = 2r'); await shot('n_mistake');
  await p.click('#cStyle button[data-v="cut"]'); await chip('cChips', 'Shares'); await shot('o_cut');
  await p.click('#bStudent'); await shot('p_student');
  await p.setViewportSize({ width: 820, height: 1180 }); await p.click('#t-orbitals'); await p.waitForTimeout(600); await shot('q_portrait');
  console.log(JSON.stringify(errs, null, 1));
  await b.close();
})();
